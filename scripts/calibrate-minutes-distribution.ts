// Regenerates shared/minutes-distribution.generated.ts from real per-gameweek minutes
// (gameweek_player_data). Read-only on the database. See server/minutes-calibration.ts.
//
// Usage: npx tsx scripts/calibrate-minutes-distribution.ts [season ...]   (default: 2025/26)
import fs from "fs";
import path from "path";
import { pool } from "../server/db";
import { calibrateMinutes, calibrateBucketMinutes } from "../server/minutes-calibration";

(async () => {
  const seasons = process.argv.slice(2).length ? process.argv.slice(2) : ["2025/26"];
  const all = [];
  for (const season of seasons) {
    const { rows } = await pool.query(
      `SELECT player_id, gameweek, minutes FROM gameweek_player_data WHERE season = $1 AND minutes IS NOT NULL`,
      [season]
    );
    // Offset each season's gameweeks so trailing windows never straddle two seasons.
    const offset = seasons.indexOf(season) * 100;
    for (const r of rows) all.push({ playerId: r.player_id + offset * 1_000_000, gameweek: r.gameweek, minutes: r.minutes });
    console.log(`${season}: ${rows.length} rows`);
  }
  const bins = calibrateMinutes(all, { window: 5, minGameweek: 6 });
  const bucketMinutes = calibrateBucketMinutes(all, { window: 5, minGameweek: 6 });
  console.log("\nBucket mean minutes:", bucketMinutes);

  console.log("\n  x range        n   meanX  E[min]  P(0)  P(1-29) P(30-59) P(60-74) P(75+)");
  for (const b of bins) {
    console.log(`  ${String(b.lo).padStart(3)}-${String(Math.min(90, Math.round(b.hi))).padEnd(3)} ${String(b.n).padStart(7)} ${b.meanX.toFixed(1).padStart(6)} ${b.meanMinutes.toFixed(1).padStart(7)} ${b.pZero.toFixed(2).padStart(5)} ${b.p1to29.toFixed(2).padStart(7)} ${b.p30to59.toFixed(2).padStart(8)} ${b.p60to74.toFixed(2).padStart(8)} ${b.p75plus.toFixed(2).padStart(6)}`);
  }

  const out = `// GENERATED by scripts/calibrate-minutes-distribution.ts — do not edit by hand.
// Calibrated on: ${seasons.join(", ")} (trailing 5-gameweek mean minutes -> next-gameweek minutes).
import type { MinutesBin } from "../server/minutes-calibration";

// Average realised minutes inside each outcome bucket.
export const BUCKET_MEAN_MINUTES = ${JSON.stringify({ zero: 0, p1to29: +bucketMinutes.p1to29.toFixed(2), p30to59: +bucketMinutes.p30to59.toFixed(2), p60to74: +bucketMinutes.p60to74.toFixed(2), p75plus: +bucketMinutes.p75plus.toFixed(2) })} as const;

export const MINUTES_BINS: MinutesBin[] = ${JSON.stringify(bins.map(b => ({ ...b, meanX: +b.meanX.toFixed(3), meanMinutes: +b.meanMinutes.toFixed(3), pZero: +b.pZero.toFixed(4), p1to29: +b.p1to29.toFixed(4), p30to59: +b.p30to59.toFixed(4), p60to74: +b.p60to74.toFixed(4), p75plus: +b.p75plus.toFixed(4) })), null, 2)};
`;
  fs.writeFileSync(path.join(process.cwd(), "shared/minutes-distribution.generated.ts"), out);
  console.log("\nWrote shared/minutes-distribution.generated.ts");
  process.exit(0);
})().catch((e) => { console.error("FATAL", e); process.exit(1); });
